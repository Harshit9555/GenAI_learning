# 5.Statistical  Operations (Core Focus)
import numpy as np
marks = np.array([78,85,90,66,72,88,95,60])
mean = np.mean(marks)
median = np.median(marks)
variance = np.var(marks)
sd = np.std(marks)
mini = np.min(marks)
maxi = np.max(marks)
range_val = maxi-mini

print(mean)
print(median)
print(variance)
print(sd)
print(mini)
print(maxi)
print(range_val)
